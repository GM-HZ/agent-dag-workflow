export type CanvasLocale = 'en' | 'zh'
export type CanvasMessage = keyof typeof chinese
export type MessageValues = Readonly<Record<string, number | string>>

export function canvasText(locale: CanvasLocale) {
  return locale === 'zh' ? chineseText : englishText
}

function chineseText(message: CanvasMessage, values?: MessageValues): string {
  return interpolate(chinese[message], values)
}

function englishText(message: CanvasMessage, values?: MessageValues): string {
  return interpolate(message, values)
}

function interpolate(text: string, values?: MessageValues): string {
  return values === undefined
    ? text
    : text.replaceAll(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder))
}

export function normalizeCanvasLocale(language: string | undefined): CanvasLocale {
  return /^zh(?:-|$)/i.test(language?.trim() ?? '') ? 'zh' : 'en'
}
